"""WorkBuddy 双端会话同步工具。

数据模型来自对 WorkBuddy 5.x 的实测逆向，以及参考项目
NextAgentX/qoder-trae-workbuddy-switch 的实现，详见 .workbuddy/memory/2026-10-29.md。

v1.5.0 起支持**真正切换登录账号**（写官方认证文件 + 重启客户端）与
**会话复制**（新 id 落一份到别的账号），依据分别是对认证文件与
`sessions` 表结构的实测。

v1.6.0 起：
- 账号入口从「⋯」菜单改为 320px 抽屉（查看 / 登录两套状态分开表达）；
- 配置同步补上 `settings.json` 的**行为开关**（技能启停、连接器开关等）——
  这是「导入后还要手动调一遍」的根因；
- 新增**本机账号对齐**（并集）：让同一台机器上的每个账号拥有同一份会话与人格。

v1.6.1 起：
- 账号对齐加入**内容判重**：同一批对话在不同账号下的副本（只是会话 id 不同）
  不再被重复复制，否则对齐后同一段对话会在侧边栏里出现两次；
- 复制会话改为**逐条勾选**：重复项照样列出来、打徽标，但默认不勾，由用户决定。

v1.6.2 起：
- 对齐页的**接收方账号可多选**：勾谁谁才收内容，未勾选的账号一个字节都不写
  （原先是「只能复制到全部账号」）；来源仍是全部账号，方便只补某个新号。

v1.6.3 起：
- **导入不再要求先手动退出客户端**：执行时会自动关闭、写完按勾选重启
  （对话框原先禁用了「执行导入」，与「导入后自动重启」自相矛盾）；
- 会话复制加入**同族识别 + 增量追加**：目标里已有同一份会话的旧版本时，
  只把缺的那几行追加上去，不再造第二份；内容分叉的交给人判断，不自动写。

v1.6.4 起：
- 「逐条选择」里**追加项也列出来**（标「可追加 N 行」），可与复制项一起逐条勾选；
  同一个目标旧版本只会被追加一次（多条源互为兄弟副本时不再写两遍）。

v1.6.5 起：
- 「前台看得见」成为统一口径：判重只看未删除的会话（目标里那条已删除 ⇒ 用户
  看不到 ⇒ 必须补），导出/复制也一律跳过已删除的会话；
- 对齐计划页**默认一个账号都不勾**（纯加法操作，不再替用户拍板占磁盘）；
- 计划改在后台线程算并显示转圈读秒（原先同步算，点进去像卡住）；
  逐行 hash 换成 blake2b-64，本机 4 账号 4.3 秒 → 0.9 秒；
- 计划页每行账号**最多两行**（「复制 N 条（约 X MB）」+「追加 … · 合并长期记忆」），
  「跳过 N 条」这类只读信息折进悬停提示；
- 工作空间页**反显已配置的映射**（原先没有失效路径时整页空白，像是记忆丢了）；
- 修掉对齐结束后结果对话框取错字段（`restart_ok`）导致抛异常、窗口不出的问题。

v1.6.11 起（按 1440×900 设计稿重做界面）：
- **账号独立成一页**（导航第六项）：四列清单（账号 / 套餐 / 会话 / 最近使用）+
  「当前账号」「切换」，抽屉退场；顶栏的账号胶囊是它的入口；
- **统一外壳**：侧栏 232 + 顶栏 64，页面标题与副标题上移顶栏，页面内不再画标题；
- **配色重做**：主绿 #16A34A、浅绿 #E9F6EE、页面 #F4F5F7、表带 #FAFBFC、
  描边 #E3E7EC；会话页筛选从绿胶囊改成深色页签（绿在这套界面里只表示「正常」）；
- **概览重排**：问候行 + 状态横幅 + 四张统计卡 + 最近备份 + 快捷操作；
- **配置页加分组带**（人格 / 设置项 / 本机设置 / 技能目录），指纹降级进 tooltip；
- **工作空间页合并成一张表**（待修 + 已记录的映射），补「最近出现」列；
- 会话页未选中时详情面板不占位，选中才让出右栏。
- **本机账号对齐改成四步向导**（选账号 → 选会话 → 确认人格与记忆 → 执行），
  **接收账号改为单选**（多选时「预计新增」永远算不准），执行搬进第 4 步。

v1.7.0（对外正式版，合并 v1.5.0–v1.6.11 的全部能力）：
- 相对上一个对外版本 v1.1.0，新增三块能力：**切换登录账号**（凭据留存 + 写官方认证文件 +
  重启，不联网、不解密信封）、**会话复制**（新 id 落第二份，原会话不动）、
  **本机账号对齐**（并集，含人格补全与长期记忆合并）；
- 会话同步补齐**四级判重**：血统（账本 new_cid→源 cid）、内容等价（归一化 digest）、
  同族旧版本（逐行 hash 公共前缀，可增量追加）、计划内判重（多源并集时同一段对话只留一条）；
- 「前台看得见」成为统一口径：清单一律按 `deleted_at IS NULL` 过滤，判重只看未删除的会话；
- 导入不再要求先手动退出客户端，且支持强制导入重复项；跨账号重复导入按「搬走」处理；
- 界面按 1440×900 重做（见上一条），账号独立成页；
- 打包侧：`push_chain.py` 作为 github.com 不可达时的发布通道（Git Data API 逐笔复现提交链）。

v1.8.0 起（含 v1.7.1 内部修订，首次对外发版）：
- **主窗尺寸按屏幕可用区自适应**：写死的 1440×932 在 125% 缩放的 1920×1080 上比可用区
  （1536×816）还高，而最小高度 1160×792 又把「手动缩小」堵死，窗口底部永远被切；
  现在先把设计稿夹进可用区、显示后按真实边框（标题栏另算）二次收紧，并记住上次几何；
- **客户端关着也能自动重启**：原本用 `primary_exe()` 取路径，它只认运行中的进程，
  客户端一关就返回空串，勾了「导入后自动重启」也静默不启动且不作任何说明；
  改为「进程 → 上次记住的路径 → 注册表/默认安装目录」三级回落，结果框补齐四种结局；
- **切换向导的「迁移内容」改成层级树**：对话(N) / 工作区(N) → 空间 → 会话，
  默认只展开到空间名；勾选支持整组生效与三态回算；
- **切换执行补上进度**：遮罩标题报「3/7 关闭 WorkBuddy…」，同一步内的细粒度进度不推步号，
  计时不再被每步重置；去掉对话框关闭后又弹的第二个确认框；
- 空间归组口径统一到 `wbsync/spaces.py`（原来散在界面层），并修掉路径大小写不同导致的
  「同一目录裂成两个同名空间」。
- **会话页工具栏不再被挤压**：筛选页签与「搜索 / 重新盘点 / 导入 / 导出 / ⋯」原本硬塞在一行，
  窗口 1080 宽且详情面板展开时列表区只剩约 530px，QHBoxLayout 把每个控件压到 minimumSizeHint
  以下，文字被裁成「地可见」这种半截；现在页签与动作组都走流式布局，放不下就整组换行，
  宽屏仍是一行且动作组右对齐；
- **账号页菜单收起「让所有账号共用同一份数据」**：它等价于跑一次「本机账号对齐」，
  两个入口并排会被当成两个功能；开关逻辑与偏好存储（`uistate`）保留，
  `accounts_page._SHOW_SHARE_OPTION` 改回 True 即恢复。
- **「清除已删除」不再出现「删了又回来了」**：`transport=cloud` 的会话删行等于抹掉
  客户端告诉云端「这条我删了」的唯一信号，客户端重启对账后会把它们重新下发
  （实测 26 条一次性回流：rowid 161–186 连续追加在表尾、`deleted_at` 仍为 -1、
  `edge_sync_mapping` 已空 —— 删行本身成功了，回流是客户端行为）。
  现在云端会话不再删行，改为**只在本工具里隐藏**：cid 记进 `uistate.hidden_sessions`，
  盘点时排除、页脚常驻「已隐藏 N 条」、「⋯ → 显示已隐藏的会话」一键恢复；
  本地会话照常物理删除。单条 / 勾选 / 全部已删除三个入口共用同一套分流
  （`purge.split_cloud`），漏掉任何一个入口都会回到老样子。
- **会话页增加「批量删除」**：工具栏常驻红描边按钮（不在 ⋯ 菜单里），
  点一下进入多选模式 —— 每行 / 每组冒出勾选框，底部动作条带「已选 N / 全选可见 /
  清空 / 云端徽标 / 删除 / 退出」。多选逻辑复用 `CardGrid` 的分组三态
  （点组标题的勾选框 = 全选本组且回算半选），`Esc` 退出；进入时强制卡片视图、
  隐藏详情面板。删除走既有 `purge.split_cloud` 分流（本地物理删、云端改隐藏），
  确认弹窗复用 `PurgeDialog`（本地 / 云端 / 字节统计、标题清单、备份勾选、风险提示），
  成功反馈改用列表顶部**内联绿色横幅**而非第二个 QMessageBox。
"""

